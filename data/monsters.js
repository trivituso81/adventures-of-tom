function monsterDef(npc) { return MONSTERS[npc.monster]||MONSTERS.grump; }
const cap=s=>s.charAt(0).toUpperCase()+s.slice(1);

function monsterLines(m) {
  const d=monsterDef(m);
  if(performance.now()<m.defeatedUntil) return d.rest;
  const lines=m.tier===0?d.talk:d.again;
  return lines.map(l=>l.replace('{n}',m.tier+1));
}
// Battle messages written for the Grump get the current monster's name swapped in.
function enemyText(s) {
  const d=battle.enemy&&battle.enemy.def; if(!d||d.id==='grump') return s;
  return s.replace(/Pond Grump/g,d.name).replace(/The Grump/g,cap(d.the)).replace(/the Grump/g,d.the).replace(/Grump/g,d.short);
}

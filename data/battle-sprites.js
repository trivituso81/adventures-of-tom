// Big (painted, 60+ row) sprites are drawn once into an offscreen canvas per (frame, palette, scale, flash, outfit tint, kneel cut)
// and then blitted, so higher detail costs one drawImage instead of thousands of fillRects.
const SPRITE_CACHE=new WeakMap();
let spriteCacheId=0;
function bigSpriteCanvas(rows,pal,scale,flash) {
  let m=SPRITE_CACHE.get(rows); if(!m) { m=new Map(); SPRITE_CACHE.set(rows,m); }
  const t=activeTint;
  const key=(pal._cid||(pal._cid=++spriteCacheId))+'|'+scale+'|'+(flash?1:0)+'|'+(t?(t.rows.join(',')+JSON.stringify(t.map)):'')+'|'+activeKneelCut;
  let c=m.get(key); if(c) return c;
  const w=Math.ceil(rows[0].length*scale)+1,h=Math.ceil(rows.length*scale)+1;
  c=document.createElement('canvas'); c.width=w; c.height=h;
  const g=c.getContext('2d');
  for(let r=0;r<rows.length;r++) {
    const row=rows[r],y0=Math.round(r*scale),y1=Math.round((r+1)*scale);
    for(let q=0;q<row.length;q++) {
      const ch=row[q]; if(ch==='.') continue;
      const x0=Math.round(q*scale),x1=Math.round((q+1)*scale);
      g.fillStyle=flash?'#fff8e6':((t&&tintColor(ch,r))||pal[ch]);
      g.fillRect(x0,y0,x1-x0,y1-y0);
    }
  }
  m.set(key,c); return c;
}
function drawSprite(rows,pal,x,y,scale,opts={}) {
  const {flash=false,alpha=1,lean=0}=opts;
  if(alpha<=0) return;
  if(rows.length>=60&&!lean) {
    const prevA=gfx.globalAlpha; gfx.globalAlpha=alpha;
    gfx.drawImage(bigSpriteCanvas(rows,pal,scale,flash),Math.round(x),Math.round(y));
    gfx.globalAlpha=prevA;
    return;
  }
  const prevAlpha=gfx.globalAlpha;
  gfx.globalAlpha=alpha;
  for(let r=0;r<rows.length;r++) {
    const row=rows[r];
    const y0=Math.round(y+r*scale),y1=Math.round(y+(r+1)*scale);
    const shift=lean?Math.round(lean*(1-r/rows.length)):0;
    for(let c=0;c<row.length;c++) {
      const ch=row[c];
      if(ch==='.') continue;
      const x0=Math.round(x+c*scale)+shift,x1=Math.round(x+(c+1)*scale)+shift;
      gfx.fillStyle=flash?'#fff8e6':((activeTint&&tintColor(ch,r))||pal[ch]);
      gfx.fillRect(x0,y0,x1-x0,y1-y0);
    }
  }
  gfx.globalAlpha=prevAlpha;
}

function setMessage(text) { b2Msg(text); }

// Fail-safe for the frame loop, the battle queue and the scene drawing: something that throws in one step, scene or frame
// must never freeze the game. The error is logged (console and window.__faults) and the player sees one short line,
// then play carries on.
function gameFault(where,err) {
  try {
    const msg=String((err&&err.message)||err).slice(0,80),key=where+'|'+msg,F=gameFault.seen||(gameFault.seen={});
    F[key]=(F[key]||0)+1;
    if(F[key]<=3) console.error('fault in '+where+': '+msg,err);
    if(F[key]!==1) return;
    const log=window.__faults||(window.__faults=[]); log.push({where,msg,at:Date.now()}); if(log.length>30) log.shift();
    const text='Hiccup in '+where+': '+msg,el=document.getElementById('toast');
    if(typeof showToast==='function') showToast(text,4.5);
    if(el) { el.textContent=text; el.classList.add('visible'); clearTimeout(gameFault.timer); gameFault.timer=setTimeout(()=>el.classList.remove('visible'),4500); }   // battle does not refresh the toast
  } catch(e) {}
}

function clearBattleQueue() {
  battle.queue.length=0;
  clearTimeout(battle.timer);
  battle.busy=false;
}

function enqueue(...steps) {
  battle.queue.push(...steps);
  if(!battle.busy) nextStep();
}

function nextStep() {
  if(!battle.active) return;
  const s=battle.queue.shift();
  if(s===undefined) { battle.busy=false; return; }
  battle.busy=true;
  if(typeof s==='string') {
    setMessage(s);
    battle.timer=setTimeout(nextStep,1150/b7Speed());
  } else if(typeof s==='number') {
    battle.timer=setTimeout(nextStep,s/b7Speed());
  } else {
    try { s(); } catch(err) { gameFault('step',err); }   // a step that throws must not strand the rest of the move
    nextStep();
  }
}

function pop(text,x,y,color) {
  battle.pops.push({text,x,y,color,t:0});
}


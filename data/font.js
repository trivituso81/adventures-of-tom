function label(text,x,y,color='#fff1cb',sc=1) {
  const chars=Array.from(String(text).toUpperCase());
  const width=(chars.length*4-1)*sc;
  let px=Math.round(x-width/2);
  const py=Math.round(y);
  gfx.fillStyle=color;
  for(const ch of chars) {
    const g=GLYPHS[ch]||GLYPHS[' '];
    for(let row=0;row<5;row++)
      for(let col=0;col<3;col++)
        if(g[row][col]==='1') gfx.fillRect(px+col*sc,py+row*sc,sc,sc);
    px+=4*sc;
  }
}

function isPath(x,y) {
  return within(currentMap,x,y) &&
    ['path','door'].includes(currentMap.tiles[y][x]);
}


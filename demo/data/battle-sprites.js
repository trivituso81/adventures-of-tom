function drawSprite(rows,pal,x,y,scale,opts={}) {
  const {flash=false,alpha=1,lean=0}=opts;
  if(alpha<=0) return;
  const prevAlpha=gfx.globalAlpha;
  gfx.globalAlpha=alpha;
  for(let r=0;r<rows.length;r++) {
    const row=rows[r];
    const y0=Math.round(y+r*scale),y1=Math.round(y+(r+1)*scale);
    const shift=lean?Math.round(lean*(1-r/rows.length)):0;
    for(let c=0;c<row.length;c++) {
      const ch=row[c];
      if(ch==='.') continue;
      const x0=Math.round(x+c*scale)+shift,x1=Math.round(x+(c+1)*scale)+shift;
      gfx.fillStyle=flash?'#fff8e6':((activeTint&&tintColor(ch,r))||pal[ch]);
      gfx.fillRect(x0,y0,x1-x0,y1-y0);
    }
  }
  gfx.globalAlpha=prevAlpha;
}


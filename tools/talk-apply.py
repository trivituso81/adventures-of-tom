#!/usr/bin/env python3
"""Build data/talk-types.js from docs/talk-lines.tsv (talk1, Tom 2026-11-13; docs/TALK_POSES.md).

    python3 tools/talk-apply.py

docs/talk-lines.tsv is the source (one row per cast dialogue line; column `talk` is tell, point, ask, answer, or empty = the line keeps its mood).
Tom's corrections are one-word edits to the `talk` column there, then rerun this tool. Never hand-edit data/talk-types.js.
Key: '<Speaker>|<text>' -> type. When the same speaker and text are talk in one chapter and not in another (or two types), the key gets '|<chapter>'
(Nine Scoops = 21, as STORY.chapter in the bonus) and the plain key is left out. Checks (fatal): known type, known speaker.
"""
import csv, json, os, sys, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/talk-lines.tsv')
OUT = os.path.join(ROOT, 'data/talk-types.js')
TYPES = ('tell', 'point', 'ask', 'answer')
SPEAKERS = {'tom', 'tnb', 'grace', 'rose', 'amy', 'justin', 'olivia', 'deedee', 'boppy', 'ellie', 'aunt ellie'}


def main():
    by = collections.defaultdict(dict); bad = []
    with open(TSV, newline='', encoding='utf-8') as fh:
        for r in csv.DictReader(fh, delimiter='\t', quoting=csv.QUOTE_NONE):
            t = r['talk'].strip(); ch = '21' if r['chapter'] == 'Nine Scoops' else r['chapter']
            if t and (t not in TYPES or r['character'].lower() not in SPEAKERS): bad.append((ch, r['character'], t, r['text'][:40])); continue
            by[(r['character'], r['text'])][ch] = t
    if bad: sys.exit('bad rows: %r' % bad[:10])
    out = {}
    for (sp, tx), chs in by.items():
        vals = set(chs.values())
        if len(vals) == 1:
            v = vals.pop()
            if v: out[sp + '|' + tx] = v
        else:
            for ch, v in chs.items():
                if v: out[sp + '|' + tx + '|' + ch] = v
    c = collections.Counter(out.values())
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write("'use strict';\n// data/talk-types.js — which talking pose a plain cast line uses (talk1, docs/TALK_POSES.md). GENERATED by tools/talk-apply.py from docs/talk-lines.tsv; do not hand-edit.\n"
                 "// TALK_TYPES['Speaker|text'] (or 'Speaker|text|chapter') = tell | point | ask | answer. A listed line shows its talk pose instead of its mood pose once the\n"
                 "// speaker's talking sheet is baked (STORY_POSES[id].tk_<type>); a line with no entry and no mood uses the same rule live (talkRule, engine/emotions.js).\n"
                 "const TALK_TYPES=" + json.dumps(out, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ";\n")
    print('wrote', os.path.relpath(OUT, ROOT), len(out), 'keys', dict(c))


if __name__ == '__main__':
    main()

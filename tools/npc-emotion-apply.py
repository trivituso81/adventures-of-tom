#!/usr/bin/env python3
"""Build data/npc-emotion-moods.js from docs/npc-emotion-lines.tsv (npcemo7, Tom 2026-11-10: "all NPC dialogue should be tagged ... implement them").

    python3 tools/npc-emotion-apply.py

The tsv is the source of every NPC mood (a correction is a one-word edit to a row there; run tools/npc-emotion-check.py, then this tool, then
tools/npc-emotion-index.py for the doc). Never hand-edit data/npc-emotion-moods.js.
Output: NPC_EMOTION_MOODS['<speaker lowercased>|<exact line text>'] = mood. engine/emotions.js reads it for every dialogue box (map talk, recruit and shop
intro lines, cab lines, townsfolk lines inside story scenes): the speaker's dialogue portrait becomes their face in that mood (portraits/emo/<id>-<mood>.webp) and
the NPC on the map is drawn in the full-body mood pose (data/npc-poses.js). A speaker with no mood face (EMOTION_FACES) shows the plain portrait.
Fatal checks (same as the check tool): valid mood, the exact text found in its file, one mood per speaker and text.
"""
import csv, json, os, subprocess, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/npc-emotion-lines.tsv')
OUT = os.path.join(ROOT, 'data/npc-emotion-moods.js')
r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools/npc-emotion-check.py')], capture_output=True, text=True)
if r.returncode: sys.exit(r.stdout[-1500:] + r.stderr[-500:] + '\nnpc-emotion-apply: the tag check failed')
out = {}
with open(TSV, newline='', encoding='utf-8') as fh:
    for row in csv.DictReader(fh, delimiter='\t', quoting=csv.QUOTE_NONE):
        out[row['character'].strip().lower() + '|' + row['text']] = row['mood']
with open(OUT, 'w', encoding='utf-8') as fh:
    fh.write("'use strict';\n// data/npc-emotion-moods.js — GENERATED by tools/npc-emotion-apply.py from docs/npc-emotion-lines.tsv. Do not hand-edit (corrections go in the tsv).\n"
             "// NPC_EMOTION_MOODS['<speaker lowercased>|<exact line text>'] = mood (engine/emotions.js).\n")
    fh.write('const NPC_EMOTION_MOODS=%s;\n' % json.dumps(out, ensure_ascii=False, indent=0))
print('wrote data/npc-emotion-moods.js', len(out), 'keys,', os.path.getsize(OUT) // 1024, 'KB')

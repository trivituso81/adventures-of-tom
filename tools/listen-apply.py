#!/usr/bin/env python3
"""Build data/listen-types.js from docs/listen-lines.tsv (listen1, card c-idea-implementlisteni, Tom 2026-11-20:
"implement listening/thinking poses (should be generated and approved in art library) for all chapter 1 talking interactions, including cut scenes").

While a line shows, the people who are NOT speaking take a listener pose (engine/emotions.js `emoListen`):
  listen  the listening pose (frame tk_listen, Art Library <id>-listen)
  think   the thinking pose (frame tk_think, Art Library <id>-think, approved for the whole cast in report c5no)
  none    no listener pose on this line (a scream, a theft in progress, a phone text): people keep whatever they had
A cell may name people: "listen grace:think" = everyone listens, Grace thinks. The first bare word is the default for that line.

The tsv is hand-judged, one row per distinct chapter line (speaker and text). A line with no row in a chapter of LISTEN_CHAPTERS gets `listen` when its
speaker stands on the map (press-A chats with townsfolk, shop and recruit lines). A row also applies when the speaker is off the map.

    python3 tools/listen-apply.py           # write data/listen-types.js
    python3 tools/listen-apply.py --check   # exit 1 if a row is malformed or a chapter 1 scene line has no row (smoke-style check)
"""
import csv, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/listen-lines.tsv')
OUT = os.path.join(ROOT, 'data/listen-types.js')
TYPES = ('listen', 'think', 'none')
CHAPTERS = [1]


def parse(cell):
    words = cell.split(); default = None; by = {}
    for w in words:
        if ':' in w:
            who, t = w.split(':', 1)
            if t not in TYPES or not who: raise ValueError(cell)
            by[who] = t
        elif w in TYPES and default is None: default = w
        else: raise ValueError(cell)
    if default is None: raise ValueError(cell)
    return default, by


def load():
    out = {}
    with open(TSV, newline='', encoding='utf-8') as fh:
        for r in csv.DictReader(fh, delimiter='\t'):
            try: parse(r['listen'])
            except ValueError: sys.exit('bad listen cell %r for %s: %s' % (r['listen'], r['speaker'], r['text']))
            out[r['speaker'] + '|' + r['text'] + '|' + r['chapter']] = ' '.join(r['listen'].split())
    return out


def scene_lines(ch):
    d = json.load(open(os.path.join(ROOT, 'data/script-index.json'), encoding='utf-8'))
    c = next(x for x in d['chapters'] if x['n'] == ch); keys = []
    for sid in c['scenes']:
        for st in d['scenes'][sid]['steps']:
            if st.get('k') == 'talk':
                for l in st['lines']: keys.append(st['who'] + '|' + l['t'] + '|' + str(ch))
    return keys


def main():
    rows = load()
    missing = [k for ch in CHAPTERS for k in scene_lines(ch) if k not in rows]
    if '--check' in sys.argv:
        if missing: print('listen: %d chapter scene lines have no row in docs/listen-lines.tsv: %s' % (len(missing), missing[:6])); sys.exit(1)
        print('listen: ok (%d rows)' % len(rows)); return
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write("'use strict';\n// data/listen-types.js: listener poses per line (listen1). GENERATED by tools/listen-apply.py from docs/listen-lines.tsv; do not hand-edit.\n"
                 "// LISTEN_TYPES['Speaker|text|chapter'] = 'listen' | 'think' | 'none', optionally followed by '<id>:<type>' for one person. Used by emoListen (engine/emotions.js).\n")
        fh.write('const LISTEN_CHAPTERS=new Set(' + json.dumps(CHAPTERS) + ');\n')
        fh.write('const LISTEN_TYPES=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
    print('wrote %s: %d rows' % (OUT, len(rows)))
    if missing: print('WARNING: no row for', missing[:6])


main()

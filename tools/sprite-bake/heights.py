"""REAL HEIGHTS (heights1, Tom 2026-11-11). data/heights.json is the one place a main character's real height is typed. This tool turns it into the
draw scale the game uses, by MEASURING the baked walk art, so a height can never drift from the art.

  python3 tools/sprite-bake/heights.py show     table: real height, measured standing rows, draw scale, rows on screen, head rows
  python3 tools/sprite-bake/heights.py write    rewrite data/walk-scale.js (run after ANY walk rebake or any change to data/heights.json)
  python3 tools/sprite-bake/heights.py check    exit 1 when data/walk-scale.js is not what `write` would produce

Rule: Tom is the baseline (drawn at scale 1). Everyone's standing figure, top of hair or cap to feet, is drawn at
(Tom's measured rows) x inches / (Tom's inches). draw scale k = that / the character's own measured standing rows.
Changing a height: edit data/heights.json, rebake that character's walk (walk_splice.py; adults' heads are pinned to Tom's, so the body must be
rebuilt), run `write`, then python3 tools/heights_test.py. Changing a head (head_adjust.py) runs `write` and the test by itself."""
import json, os, re, sys
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
SRC, OUT = os.path.join(ROOT, 'data', 'heights.json'), os.path.join(ROOT, 'data', 'walk-scale.js')
PAT = re.compile(r'''ow["']?\s*:\s*\{\s*["']?src["']?\s*:\s*["']([^"']+)["']\s*,\s*["']?k["']?\s*:\s*([0-9.]+)\s*,\s*["']?rects["']?\s*:\s*\{\s*"down_stand"\s*:\s*\[([^\]]+)\]''')

def stand(cid):
    """(RGBA front stand frame as the game draws it, atlas px per row) from the committed walk atlas."""
    m = PAT.search(open(os.path.join(ROOT, 'data', cid + '-hires.js')).read()); assert m, cid + ': no walk atlas in data/%s-hires.js' % cid
    x, y, w, h = [int(float(v)) for v in m.group(3).split(',')]
    return Image.open(os.path.join(ROOT, m.group(1))).convert('RGBA').crop((x, y, x + w, y + h)), float(m.group(2))

def rows(cid):
    """Visible standing height in bake rows: top of hair or cap to the soles."""
    im, k = stand(cid); ys = np.where((np.array(im)[:, :, 3] > 40).any(1))[0]
    return (ys.max() - ys.min() + 1) / k

def table():
    H = json.load(open(SRC)); inch, base = H['inches'], H['baseline']; base_rows = rows(base); out = {}
    for cid in inch:
        r = rows(cid); want = base_rows * inch[cid] / inch[base]
        out[cid] = {'inches': inch[cid], 'rows': round(r, 3), 'k': 1 if cid == base else round(want / r, 4)}
    return out

def text():
    t = table()
    return ("'use strict';\n// data/walk-scale.js: GENERATED by tools/sprite-bake/heights.py write. Do not hand-edit.\n"
            "// Real heights come from data/heights.json (the one place a height is typed). Tom is the baseline at scale 1; every painted walk set is drawn at\n"
            "// k = Tom's standing rows x inches / Tom's inches / the set's own standing rows (measured on the baked art), so each figure is its real height\n"
            "// next to Tom at any head size. Loads after the last *-hires-use.js file and sets OW.<id>.k for everyone listed.\n"
            "const WALK_SCALE={\n" + ''.join("  %s:{inches:%d,rows:%s,k:%s},\n" % (c, v['inches'], v['rows'], v['k']) for c, v in t.items()) +
            "};\nfor(const id in WALK_SCALE) if(OW[id]) OW[id].k=WALK_SCALE[id].k;\n")

if __name__ == '__main__':
    cmd = sys.argv[1] if len(sys.argv) > 1 else 'show'
    if cmd == 'write': open(OUT, 'w').write(text()); print('wrote', OUT)
    elif cmd == 'check':
        if not os.path.exists(OUT) or open(OUT).read() != text(): sys.exit('data/walk-scale.js is stale: run python3 tools/sprite-bake/heights.py write')
        print('data/walk-scale.js is current')
    else:
        t = table(); b = json.load(open(SRC))['baseline']
        for c, v in t.items(): print('%-8s %d\'%d"  stand %6.2f rows  k %.4f  on screen %5.2f rows' % (c, v['inches'] // 12, v['inches'] % 12, v['rows'], v['k'], v['rows'] * v['k']))

#!/usr/bin/env python3
"""Grace extra battle poses for Open Strings (violin), Portrait Mode (sketchbook) and Bedazzle Blast (rhinestone gun), Oct 30 2026.
Reuses bake_grace.py's slicing and helpers (robust magenta cut for her violet leotard).
Input : src/grace-violin-v1.png, src/grace-portrait-v1.png, src/grace-bedazzle-v1.png (4 x 4 sheets, magenta background)
Output: art/chars/grace-extra.webp, data/grace-extra.js (GRACE_EXTRA = {atlas, pal, rows}); do not hand-edit the output.
Usage : python3 tools/sprite-bake/bake_grace_extra.py [SHEET=<png> for a grey contact sheet]"""
import os, sys, json
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'bake_grace.py')).read()
cut = src.index('# ---------------------------------------------------------------- battle set')
sys.argv = sys.argv[:1]
g = {'__name__': 'bake_grace_base', '__file__': os.path.join(here, 'bake_grace.py')}
exec(src[:cut], g)
from sheet import slice_sheet
from PIL import Image
import numpy as np
poses, KB, SRC, ART, ROOT = g['poses'], g['KB'], g['SRC'], g['ART'], g['ROOT']
scaled_to, place, tighten, rows_of, pack, fmt_rows = g['scaled_to'], g['place'], g['tighten'], g['rows_of'], g['pack'], g['fmt_rows']
fb = g['args'].battle_h * KB / poses['b_idle'].height

OS = ['os_arrive', 'os_tuck', 'os_breath', 'os_stroke', 'os_wince', 'os_sawup', 'os_sawdown', 'os_screech',
      'os_slip', 'os_push', 'os_finish', 'os_listen', 'os_shrug', 'os_lessons', 'os_bow', 'os_proud']
PM = ['pm_arrive', 'pm_open', 'pm_measure', 'pm_pose', 'pm_sketchA', 'pm_sketchB', 'pm_compare', 'pm_sketchC',
      'pm_erase', 'pm_sign', 'pm_jab', 'pm_tear', 'pm_admire', 'pm_shield', 'pm_wink', 'pm_leave']
BZ = ['bz_arrive', 'bz_draw', 'bz_load', 'bz_safety', 'bz_aim', 'bz_fireA', 'bz_sweeplow', 'bz_sweephigh',
      'bz_fireB', 'bz_onehand', 'bz_blow', 'bz_inspect', 'bz_notenough', 'bz_topup', 'bz_admire', 'bz_pose']
SHEETS = [('grace-violin-v1.png', OS, 'os_tuck'), ('grace-portrait-v1.png', PM, 'pm_leave'), ('grace-bedazzle-v1.png', BZ, 'bz_arrive')]

def body_h(img):
    """Height of the figure from the top of the head to the feet, ignoring anything held above the head: the widest
    vertical run that holds the leotard (violet) and the shoes (white) is the body; use alpha rows from the first
    violet row minus a head allowance. Simpler: the alpha height of the frame, used only on frames where nothing rises above the head."""
    al = np.array(img)[:, :, 3] > 40
    ys = np.where(al.any(1))[0]
    return ys.max() - ys.min() + 1

big = {}
for fn, names, ref in SHEETS:
    cut_ = slice_sheet(os.path.join(SRC, fn), [names[0:4], names[4:8], names[8:12], names[12:16]], robust=True)
    r = poses['b_idle'].height / body_h(cut_[ref])
    print(fn, 'scale', round(fb * r, 3), 'ref', ref, cut_[ref].size, 'idle', poses['b_idle'].size)
    for k in names: big[k] = scaled_to(cut_[k], fb * r)
big = tighten(place(big, KB, 'head'), KB)
pal, rows = rows_of(big, KB, 46)
rects = pack(big, os.path.join(ART, 'grace-extra.webp'))
js = ["'use strict';",
      "// data/grace-extra.js: Grace's painted frames for Open Strings (os_), Portrait Mode (pm_) and Bedazzle Blast (bz_). GENERATED by tools/sprite-bake/bake_grace_extra.py; do not hand-edit.",
      "const GRACE_EXTRA={atlas:" + json.dumps({'src': 'art/chars/grace-extra.webp', 'k': KB, 'rects': rects}) + ",pal:" + json.dumps(pal) + ",rows:{"]
for k, r in rows.items(): js.append(f"  {k}:" + fmt_rows(r) + ",")
js.append("}};")
open(os.path.join(ROOT, 'data/grace-extra.js'), 'w').write('\n'.join(js) + '\n')
print('wrote data/grace-extra.js', len(rows), 'frames', big[OS[0]].size)
if os.environ.get('SHEET'):
    names = list(big); w, h = big[names[0]].size; per = 8
    sh = Image.new('RGBA', (per * w, -(-len(names) // per) * h), (90, 90, 90, 255))
    for i, n in enumerate(names): sh.alpha_composite(big[n], ((i % per) * w, (i // per) * h))
    sh.save(os.environ['SHEET']); print('sheet', os.environ['SHEET'], sh.size)

#!/usr/bin/env python3
"""Grace's ability frames in battle (Tom 2026-11-06: "incorporate Grace's approved ability animations"). Replaces bake_grace_extra.py and the
cartwheel poses of bake_grace_poses.py.
Input : the 14 approved Art Library sheets art/raw/characters/grace-ab-<move>-v<n>.png, cut by grace_ability_frames.py (as painted)
Output: art/chars/grace-ab.webp (every frame on its own tight canvas, feet on the bottom row, head on the centre column, at the battle sheets' scale)
        data/grace-ab.js (GRACE_AB = {atlas, pal, rows}); do not hand-edit. Frames are named ab_<short>_<n> (see SHEETS in grace_ability_frames.py).
Run through hires.py (README, 'Sheets to install': grace-ab)."""
import os, sys, json
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'bake_grace_walk_v4.py')).read()
cut = src.index('# ---------------------------------------------------------------- battle set')
sys.argv = sys.argv[:1]
g = {'__name__': 'bake_grace_base', '__file__': os.path.join(here, 'bake_grace_walk_v4.py')}
exec(src[:cut], g)
from PIL import Image
import numpy as np
from grace_ability_frames import build as _build_ab
poses, KB, ART, ROOT = g['poses'], g['KB'], g['ART'], g['ROOT']
scaled_to, rows_of, fmt_rows, head_cx, up = g['scaled_to'], g['rows_of'], g['fmt_rows'], g['head_cx'], g['up']
fb = g['BT_IDLE_ROWS'] * KB / poses['b_idle'].height

def own_canvas(img, k):
    ax = head_cx(img); half = up(int(np.ceil(max(ax, img.width - ax))) + 1, k)
    c = Image.new('RGBA', (half * 2, up(img.height, k)), (0, 0, 0, 0))
    c.alpha_composite(img, (int(round(half - ax)), c.height - img.height))
    return c

def pack_shelf(frames, path, maxw=2048):
    x = y = rowh = 0; place_at = {}
    for n, im_ in frames.items():
        if x + im_.width > maxw: x = 0; y += rowh; rowh = 0
        place_at[n] = (x, y); x += im_.width; rowh = max(rowh, im_.height)
    atlas = Image.new('RGBA', (maxw, y + rowh), (0, 0, 0, 0)); rects = {}
    for n, im_ in frames.items():
        atlas.paste(im_, place_at[n]); rects[n] = [place_at[n][0], place_at[n][1], im_.width, im_.height]
    W = max(r[0] + r[2] for r in rects.values()); atlas = atlas.crop((0, 0, W, atlas.height))
    atlas.save(path, 'WEBP', lossless=True, quality=100, method=6)
    print('wrote', os.path.relpath(path, ROOT), atlas.size, os.path.getsize(path) // 1024, 'KB')
    return rects

big = {n: own_canvas(scaled_to(im, fb), KB) for n, im in _build_ab().items()}
pal, rows = rows_of(big, KB, 46)
rects = pack_shelf(big, os.path.join(ART, 'grace-ab.webp'))
js = ["'use strict';",
      "// data/grace-ab.js: Grace's 93 painted ability frames (14 sheets, art/raw/characters/grace-ab-*). GENERATED by tools/sprite-bake/bake_grace_ab.py; do not hand-edit.",
      "const GRACE_AB={atlas:" + json.dumps({'src': 'art/chars/grace-ab.webp', 'k': KB, 'rects': rects}) + ",pal:" + json.dumps(pal) + ",rows:{"]
for k, r in rows.items(): js.append(f"  {k}:" + fmt_rows(r) + ",")
js.append("}};")
open(os.path.join(ROOT, 'data/grace-ab.js'), 'w').write('\n'.join(js) + '\n')
print('wrote data/grace-ab.js', len(rows), 'frames')

#!/usr/bin/env python3
"""Bake Nara's painted ability frames into the game: art/chars/nara-ab.webp (painted frames) + data/nara-ab.js (small quantized rows, mouth points, atlas rects).

Input : the 14 approved Art Library sheets (see ability_frames_nara.py). Only the frames engine/nara.js names (f:'ab_<move>_<n>') are baked; the rest of each sheet is left out.
Scale : the same as her battle atlas (art/chars/nara-battle.webp: k 3, idle 84 rows tall), read from data/nara-hires.js, and the rows reuse its palette.
Marks : the mouth point (where a held prop sits) is the nose tip: the leftmost pixel of the upper figure (every frame faces screen-left).
Usage : python3 tools/sprite-bake/bake_nara_ab.py
"""
import json, os, re, sys
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ability_frames_nara import build as _build_ab, _rs
from battle_sheet_frames import build as _battle

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ART = os.path.join(ROOT, 'art/chars'); OUT = os.path.join(ROOT, 'data/nara-ab.js')
KEYS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
BATTLE_H = 84

hires = open(os.path.join(ROOT, 'data/nara-hires.js')).read()
AT = json.loads(re.search(r'atlas:(\{.*\}),\n  bt:', hires).group(1))
K = AT['bt']['k']
PAL = json.loads(re.search(r'bt:\{pal:(\{.*?\}),\n', hires).group(1))
used = sorted(set(re.sub(r'F$', '', n) for n in re.findall(r"'(ab_[a-z]+_\d)F?'", open(os.path.join(ROOT, 'engine/nara.js')).read())))

def scaled_to(img, f):
    w, h = max(1, round(img.width * f)), max(1, round(img.height * f))
    arr = np.array(img).astype(float); al = arr[:, :, 3:4] / 255.0
    pm = Image.fromarray((arr[:, :, :3] * al).clip(0, 255).astype(np.uint8), 'RGB').resize((w, h), Image.LANCZOS)
    alr = Image.fromarray(arr[:, :, 3].astype(np.uint8), 'L').resize((w, h), Image.LANCZOS)
    pa, aa = np.array(pm).astype(float), np.array(alr).astype(float) / 255.0
    rgb = np.where(aa[:, :, None] > 0.02, pa / np.maximum(aa[:, :, None], 0.02), 0)
    return Image.fromarray(np.dstack([np.clip(rgb, 0, 255), aa * 255]).astype(np.uint8), 'RGBA')

def up(n, k): return -(-n // k) * k

def own_canvas(img, k):
    """Own tight canvas, a multiple of k, figure centred on its bounding box, feet on the bottom row (the battle atlas centres the same way)."""
    w, h = up(img.width + 2, k), up(img.height, k)
    c = Image.new('RGBA', (w, h), (0, 0, 0, 0)); c.alpha_composite(img, ((w - img.width) // 2, h - img.height)); return c

def rows_in_palette(img, k):
    keys = list(PAL); pf = np.array([[int(PAL[c][i:i + 2], 16) for i in (1, 3, 5)] for c in keys]).astype(int)
    a = np.array(scaled_to(img, 1.0 / k)); a[:, :, 3] = np.where(a[:, :, 3] >= 128, 255, 0); h, w = a.shape[:2]
    d = ((a[:, :, :3].astype(int).reshape(-1, 1, 3) - pf[None, :, :]) ** 2).sum(2).argmin(1).reshape(h, w)
    return [''.join(keys[d[y, x]] if a[y, x, 3] > 0 else '.' for x in range(w)) for y in range(h)]

def pack_shelf(frames, path, maxw=2048):
    x = y = rowh = 0; at = {}
    for n, im in frames.items():
        if x + im.width > maxw: x = 0; y += rowh; rowh = 0
        at[n] = (x, y); x += im.width; rowh = max(rowh, im.height)
    atlas = Image.new('RGBA', (maxw, y + rowh), (0, 0, 0, 0)); rects = {}
    for n, im in frames.items():
        atlas.paste(im, at[n]); rects[n] = [at[n][0], at[n][1], im.width, im.height]
    atlas = atlas.crop((0, 0, max(r[0] + r[2] for r in rects.values()), atlas.height))
    atlas.save(path, 'WEBP', lossless=True, quality=100, method=6)
    print('wrote', os.path.relpath(path, ROOT), atlas.size, os.path.getsize(path) // 1024, 'KB'); return rects

def fmt_rows(rows): return '[\n' + ',\n'.join("    '" + r + "'" for r in rows) + '\n  ]'

if __name__ == '__main__':
    ready = _battle('nara', run_from_walk=False)['b_ready']
    fb = BATTLE_H * K / ready.height
    allf = _build_ab(); missing = [n for n in used if n not in allf]; assert not missing, missing
    big = {n: own_canvas(scaled_to(allf[n], fb), K) for n in used}
    rows = {n: rows_in_palette(big[n], K) for n in used}
    marks = {}
    for n, r in rows.items():
        H, W = len(r), len(r[0]); best = None
        for y in range(int(H * .62)):
            x = r[y].find(next((c for c in r[y] if c != '.'), '.'))
            if r[y].strip('.') and (best is None or x < best[0]): best = (x, y)
        mx, my = best; marks[n] = {'mouth': [mx + 1, my + 3], 'eye': [min(W - 1, mx + round(W * .17)), max(0, my - round(H * .06))]}
    rects = pack_shelf(big, os.path.join(ART, 'nara-ab.webp'))
    js = ["'use strict';",
          "// data/nara-ab.js — Nara's painted ability frames (14 approved Art Library sheets, Nov 2026). GENERATED by tools/sprite-bake/bake_nara_ab.py; do not hand-edit.",
          "// rows share the palette of NARA_HIRES.bt; atlas = art/chars/nara-ab.webp; marks = nose tip (what she carries) and a rough eye point.",
          "const NARA_AB={",
          "  atlas:" + json.dumps({'src': 'art/chars/nara-ab.webp', 'k': K, 'rects': rects}) + ",",
          "  marks:" + json.dumps(marks) + ",",
          "  ab:{" + ",".join(f"{n}:" + fmt_rows(rows[n]) for n in used) + "}", "};"]
    open(OUT, 'w').write('\n'.join(js) + '\n'); print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB', len(used), 'frames')

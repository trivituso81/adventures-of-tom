#!/usr/bin/env python3
"""Install the approved Flight pictures from the Art Library (CHANGES 156, flight2).

The old bake (bake_flight.py) expects the first generator's red-stripe plane and transparent strips, so it cannot read
the Art Library pictures. This bake uses the exact cut Tom approved in the Flight preview: it opens flight-preview.html
in headless Chromium, runs its loadLibrary() (approved files from data/art-prompts.json -> prepare(): plain pads keyed off
the strips, runway band found, plane sheet keyed and cut into 9 poses with anchors, props sheet keyed and named, map pin
spots from MAP_SPOTS), then saves each prepared layer as art/flight/*.webp and writes data/flight-art.js.

Needs the game served on localhost:8000 (python3 tools/serve.py). Run from the repo root:
  python3 tools/sprite-bake/bake_flight_lib.py
A new map version needs its pin spots added to MAP_SPOTS in flight-preview.html first.
"""
import base64, io, json, os, sys
from playwright.sync_api import sync_playwright
from PIL import Image

VER = sys.argv[1] if len(sys.argv) > 1 else '20261103'
FILES = {"cabin": "cabin.webp", "skyLe": "sky-le.webp", "skyLa": "sky-la.webp", "skylineLe": "skyline-le.webp",
         "skylineLa": "skyline-la.webp", "foreLe": "fore-le.webp", "foreLa": "fore-la.webp", "groundLe": "ground-le.webp",
         "groundLa": "ground-la.webp", "plane": "plane.webp", "props": "mapprops.webp", "map": "usmap.webp"}
# Plane poses are mirrored to nose-left (what the engine expects) inside flight-preview.html prepPlane (mirrorX).
OPAQUE = {"cabin", "skyLe", "skyLa", "groundLe", "groundLa", "map"}

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page()
    errs = []
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto('http://localhost:8000/flight-preview.html', wait_until='load')
    pg.wait_for_timeout(1500)
    res = pg.evaluate("""async()=>{
      const R=await loadLibrary(false), out={};
      for(const k of Object.keys(R.imgs)){
        const im=R.imgs[k]; const c=document.createElement('canvas');
        c.width=im.naturalWidth||im.width; c.height=im.naturalHeight||im.height;
        c.getContext('2d').drawImage(im,0,0); out[k]=c.toDataURL('image/png');
      }
      return {M:R.M, imgs:out, used:R.used};
    }""")
    b.close()
if errs:
    sys.exit('page errors: ' + '; '.join(errs))

M = res['M']
size = {}
for k, fn in FILES.items():
    im = Image.open(io.BytesIO(base64.b64decode(res['imgs'][k].split(',', 1)[1])))
    im = im.convert('RGB') if k in OPAQUE else im.convert('RGBA')
    im.save(os.path.join('art', 'flight', fn), quality=90, method=6, **({'exact': False} if im.mode == 'RGBA' else {}))
    size[k] = [im.width, im.height]
    print(f'{k:10s} {fn:16s} {im.width} x {im.height}')

meta = {"v": VER, "files": FILES, "size": size, "sun": M['sun'], "runway": M['runway'], "plane": M['plane'],
        "props": M['props'], "map": M['map']}
src = ("'use strict';\n"
       "// data/flight-art.js: GENERATED by tools/sprite-bake/bake_flight_lib.py from the approved Art Library pictures. Do not edit by hand.\n"
       "// Sizes and anchors for the painted flight scene (art/flight/*.webp). Drawn by engine/flight-art.js.\n"
       "const FLIGHT_ART_META=" + json.dumps(meta, separators=(',', ':')) + ";\n")
open('data/flight-art.js', 'w').write(src)
print('used:', '; '.join(f'{a}: {b}' for a, b in res['used']))

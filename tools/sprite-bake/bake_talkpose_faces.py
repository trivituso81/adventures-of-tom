#!/usr/bin/env python3
"""Talking-pose faces (Tom 2026-11-14, reports r-20261114-100449-r0ib and r-20261114-150823-54vk): "Talking frames should also always update the portrait image
in the dialog box ... a cropped version, just like we do with all the emotional states."

Each talking frame (art/talk/<id>.webp: tell, point, ask, answer, side by side) is cropped to the head with the SAME method and zoom as the mood faces
(bake_emotion_faces.py: hero-portrait zoom, the frame's own top row), so a face is the same size in every pose. Output portraits/talk/pose/<id>-<type>.webp
(256 x 256) and data/talkpose-faces.js (ids that have them). engine/emotions.js shows the face on a line that plays that talking pose.
    python3 tools/sprite-bake/bake_talkpose_faces.py [ids]     CHECK=/tmp/tp.png  writes a contact sheet (plain talk face, then the 4 poses, per person)
"""
import os, sys, json
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bake_emotion_faces as BE

ROOT = BE.ROOT
SRC = os.path.join(ROOT, 'art', 'talk')
TYPES = ['tell', 'point', 'ask', 'answer']
BE.OUT = os.path.join(ROOT, 'portraits', 'talk', 'pose')
BE.MOODS = TYPES
BE.MOOD_DY = {t: float(os.environ.get('DY', '0.03')) for t in TYPES}
BE.head_scale = lambda pid: float(os.environ.get('HS', '1.0'))


def frames(pid):
    sh = Image.open(os.path.join(SRC, pid + '.webp')).convert('RGBA'); fw = sh.width // 4
    return [sh.crop((i * fw, 0, (i + 1) * fw, sh.height)) for i in range(4)]


BE.frames = frames


def main():
    ids = sys.argv[1:] or sorted(f[:-5] for f in os.listdir(SRC) if f.endswith('.webp'))
    rows = []
    for pid in ids:
        outs = BE.bake(pid)
        tf = os.path.join(ROOT, 'portraits', 'talk', pid + '.webp')
        rows.append([Image.open(tf).convert('RGB')] + outs); print('baked', pid)
    chk = os.environ.get('CHECK')
    if chk:
        w = 160; sheet = Image.new('RGB', (w * 5, w * len(rows)), 'white')
        for r, row in enumerate(rows):
            for i, c in enumerate(row): sheet.paste(c.resize((w, w), Image.LANCZOS), (i * w, r * w))
        sheet.save(chk); print('wrote', chk)
    if not sys.argv[1:]:
        with open(os.path.join(ROOT, 'data', 'talkpose-faces.js'), 'w') as fh:
            fh.write("'use strict';\n// data/talkpose-faces.js: people with a dialogue face for each talking pose (portraits/talk/pose/<id>-<type>.webp). GENERATED by tools/sprite-bake/bake_talkpose_faces.py; do not hand-edit.\n"
                     "const TALKPOSE_FACES=%s;\n" % json.dumps(ids))


if __name__ == '__main__':
    main()

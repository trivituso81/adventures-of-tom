#!/usr/bin/env python3
"""Bake young Boppy (Van Cortlandt Park '70 flashback, xc_ult) into the game: art/chars/boppy-young.webp + data/boppy-young.js (BOPPY_YOUNG).

Input : art/raw/characters/boppy-young-battle-sheet-1-v1.png and -2-v1.png (approved Art Library sheets, cut by battle_sheet_frames.py) and
        All used as painted: no head or body resizing, no flipping.
Frames: ready (b_ready), wind (b_wind, the start-line lean), celebr (b_cheer, fist up, hand on hip). No run frames: the stage holds the stance on a keyed slide
        (engine/battle-draw.js), so youngOn() in engine/boppy-moves.js puts ready in place of idle while he runs. Tom's walk sheet (boppy-young-walk-sheet-ref-v1.png) is a Library reference only.
Scale : same person as adult Boppy (5'7), so the young ready pose is as tall as adult Boppy's in-game idle (art/chars/boppy-battle.webp, same k). Sheet 2 is sized to
        sheet 1 by battle_sheet_frames.
Rows  : quantized to adult Boppy's battle palette (BOPPY_HIRES.bt.pal), like his ability frames; data/boppy-hires-battle.js registers them as sp.yg_<name>.
Usage : python3 tools/sprite-bake/bake_boppy_young.py [--check]   (--check writes /tmp/w/young_boppy_frames.png and /tmp/w/young_boppy_headrow.png)
"""
import json, os, re, sys
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from battle_sheet_frames import build as _battle, RAW
from bake_boppy_ab import scaled_to, own_canvas, pack_shelf, rows_in_palette, fmt_rows, AT, K, ART, ROOT
OUT = os.path.join(ROOT, 'data/boppy-young.js')

def frames():
    b = _battle('boppy-young', run_from_walk=False)
    return {'ready': b['b_ready'], 'wind': b['b_wind'], 'celebr': b['b_cheer']}

def adult_idle():
    r = AT['bt']['rects']['idle']; im = Image.open(os.path.join(ART, 'boppy-battle.webp')).crop((r[0], r[1], r[0] + r[2], r[1] + r[3]))
    return im.crop(im.getbbox())

if __name__ == '__main__':
    fr = frames(); idle = adult_idle()
    f = idle.height / fr['ready'].height
    print('young scale', round(f, 4), 'adult idle h', idle.height)
    big = {n: own_canvas(scaled_to(im, f), K) for n, im in fr.items()}
    rows = {n: rows_in_palette(big[n], K) for n in big}
    rects = pack_shelf(big, os.path.join(ART, 'boppy-young.webp'))
    js = ["'use strict';",
          "// data/boppy-young.js — young Boppy for the Van Cortlandt Park '70 flashback (approved Art Library battle sheets, Nov 2026). GENERATED by tools/sprite-bake/bake_boppy_young.py; do not hand-edit.",
          "// rows share the palette of BOPPY_HIRES.bt; atlas = art/chars/boppy-young.webp; data/boppy-hires-battle.js registers them as sp.yg_<name>.",
          "const BOPPY_YOUNG={",
          "  atlas:" + json.dumps({'src': 'art/chars/boppy-young.webp', 'k': K, 'rects': rects}) + ",",
          "  rows:{" + ",".join(f"{n}:" + fmt_rows(rows[n]) for n in big) + "}", "};"]
    open(OUT, 'w').write('\n'.join(js) + '\n'); print('wrote', os.path.relpath(OUT, ROOT), os.path.getsize(OUT) // 1024, 'KB')
    if '--check' in sys.argv:
        os.makedirs('/tmp/w', exist_ok=True)
        ks = list(big); W = sum(big[k].width + 12 for k in ks); H = max(big[k].height for k in ks)
        sh = Image.new('RGBA', (W, H + 4), (128, 128, 128, 255)); x = 0
        for k in ks: sh.alpha_composite(big[k], (x, H + 4 - big[k].height)); x += big[k].width + 12
        sh.convert('RGB').save('/tmp/w/young_boppy_frames.png')
        row = [idle] + [big[k].crop(big[k].getbbox()) for k in ('ready', 'wind', 'celebr')]
        W = sum(im.width + 20 for im in row); H = max(im.height for im in row)
        sh = Image.new('RGBA', (W, H + 10), (128, 128, 128, 255)); x = 10
        for im in row: sh.alpha_composite(im, (x, H + 5 - im.height)); x += im.width + 20
        sh.convert('RGB').save('/tmp/w/young_boppy_headrow.png')

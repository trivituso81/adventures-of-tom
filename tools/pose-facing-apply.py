#!/usr/bin/env python3
"""Build data/pose-facing.js from docs/pose-facing.tsv (facing1, Tom 2026-11-14).

    python3 tools/pose-facing-apply.py           # write data/pose-facing.js
    python3 tools/pose-facing-apply.py --check   # exit 1 if a baked mood or talking frame has no row (smoke runs this)

Tom 2026-11-14 08:39 (chapter 1 grey grass): "only Grace should be facing right ... everyone else should be mirror image."
Painted mood poses (em_*) and talking poses (tk_*) lean whichever way the generator painted them. docs/pose-facing.tsv says, per
person and frame, which way the painting leans: l (face or gesture turned to screen left), r (to screen right), f (front, never mirrored).
The engine (engine/story.js scenePoseDraw, poseFacingWant) mirrors an l or r frame when the person should face the other way.
The tsv is hand-judged (looked at frame by frame). A new sheet: add its rows by looking at the frames (CHECK sheet), never by guessing.
Tom's corrections: change one `lean` cell, rerun this tool, push.
"""
import csv, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/pose-facing.tsv')
OUT = os.path.join(ROOT, 'data/pose-facing.js')
SRC = ['data/story-poses.js', 'data/npc-poses.js']


def baked():
    out = set()
    for f in SRC:
        s = open(os.path.join(ROOT, f), encoding='utf-8').read()
        for m in re.finditer(r'\n  \w+:\{member:"?(\w*)"?,atlas:(\{.*?\}\})', s):
            for k in json.loads(m.group(2))['rects']:
                if k.startswith(('em_', 'tk_')): out.add((m.group(1), k))
    return out


def main():
    rows = {}
    with open(TSV, newline='', encoding='utf-8') as fh:
        for r in csv.DictReader(fh, delimiter='\t'):
            if r['lean'] not in ('l', 'r', 'f'): sys.exit('bad lean %r for %s %s' % (r['lean'], r['id'], r['frame']))
            rows[(r['id'], r['frame'])] = r['lean']
    missing = sorted(baked() - set(rows))
    if '--check' in sys.argv:
        if missing: print('pose-facing: %d baked frames have no lean in docs/pose-facing.tsv: %s' % (len(missing), missing[:12])); sys.exit(1)
        print('pose-facing: ok (%d frames)' % len(rows)); return
    data = {i + '|' + f: v for (i, f), v in sorted(rows.items()) if v != 'f'}
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write("'use strict';\n// data/pose-facing.js: which way each painted mood or talking pose leans (facing1). GENERATED by tools/pose-facing-apply.py from docs/pose-facing.tsv; do not hand-edit.\n"
                 "// POSE_FACING['<id>|<frame>'] = 'l' or 'r' (screen side the painting is turned to). Missing = front, drawn as painted.\n")
        fh.write('const POSE_FACING=' + json.dumps(data, separators=(',', ':')) + ';\n')
    print('wrote %s: %d leaning frames of %d' % (OUT, len(data), len(rows)))
    if missing: print('WARNING: no row for', missing)


main()

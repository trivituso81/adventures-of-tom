#!/usr/bin/env python3
"""Build data/emotion-moods.js from docs/emotion-index-lines.tsv for the chapters switched on (emo7, Tom 2026-11-06).

    python3 tools/emotion-apply.py 1            # batch 0: chapter 1 only
    python3 tools/emotion-apply.py 1 2 3 4      # later batches are cumulative: every chapter that is on, Nine Scoops is chapter 21 (STORY.chapter in the bonus), pass 21

The tsv is the source of every mood (Tom's corrections are one-word edits to a row there, then rerun this tool and tools/emotion-index.py's doc if present).
Never hand-edit data/emotion-moods.js. Rows tagged `none` are left out (that line shows the plain portrait).
Checks, all fatal: every kept row's speaker is a known portrait speaker; its exact text is found in the row's scene file (JS string escapes undone);
the same speaker and text carry one mood per chapter (a second mood gets a `|<chapter>` key automatically, and the plain key is dropped if the two chapters disagree).
Prints found / expected per chapter.
"""
import csv, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/emotion-index-lines.tsv')
OUT = os.path.join(ROOT, 'data/emotion-moods.js')
MOODS = {"happy", "loving", "sad", "angry", "scared", "surprised", "proud", "unimpressed"}
SPEAKERS = {'tom', 'tnb', 'grace', 'rose', 'amy', 'justin', 'olivia', 'deedee', 'boppy', 'ellie', 'aunt ellie', 'nara'}


def norm(src):
    src = re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), src)
    return src.replace("\\'", "'").replace('\\"', '"').replace("\\\\", "\\")


def main():
    want = [a for a in sys.argv[1:]]
    if not want: sys.exit(__doc__)
    cache, rows = {}, []
    with open(TSV, newline='', encoding='utf-8') as fh:
        for r in csv.DictReader(fh, delimiter='\t', quoting=csv.QUOTE_NONE):
            ch = '21' if r['chapter'] == 'Nine Scoops' else r['chapter']
            if ch in want: rows.append((ch, r))
    miss, expected, found, bad = [], {}, {}, []
    moods = {}   # (speaker, text) -> {chapter: mood}
    for ch, r in rows:
        if r['mood'] == 'none': continue
        sp, tx, md = r['character'], r['text'], r['mood']
        if md not in MOODS or sp.lower() not in SPEAKERS: bad.append((ch, sp, md, tx[:40])); continue
        expected[ch] = expected.get(ch, 0) + 1
        f = r['file']
        if f not in cache: cache[f] = norm(open(os.path.join(ROOT, f), encoding='utf-8').read())
        if tx in cache[f]: found[ch] = found.get(ch, 0) + 1
        else: miss.append((ch, sp, tx[:70]))
        moods.setdefault((sp, tx), {})
        if moods[(sp, tx)].get(ch, md) != md: bad.append((ch, sp, 'two moods for the same line', tx[:40]))
        moods[(sp, tx)][ch] = md
    for ch in want: print('chapter', ch, 'found', found.get(ch, 0), 'of', expected.get(ch, 0))
    if miss or bad:
        for m in miss: print('MISSING', m)
        for b in bad: print('BAD', b)
        sys.exit('emotion-apply: fix the above (zero missing, zero bad) before committing')
    out = {}
    for (sp, tx), per in sorted(moods.items()):
        vals = set(per.values())
        if len(vals) == 1: out[sp + '|' + tx] = vals.pop()
        else:
            for ch, md in per.items(): out[sp + '|' + tx + '|' + ch] = md
    chs = [int(c) if c.isdigit() else c for c in want]
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write("'use strict';\n// data/emotion-moods.js — GENERATED by tools/emotion-apply.py from docs/emotion-index-lines.tsv. Do not hand-edit (Tom's corrections go in the tsv).\n"
                 "// EMOTION_MOODS['<Speaker>|<exact line text>'] = mood (a key ending |<chapter> applies to that chapter only). EMO_CHAPTERS: the chapters switched on (engine/emotions.js).\n")
        fh.write("const EMO_CHAPTERS=new Set(%s);\n" % json.dumps(chs))
        fh.write("const EMOTION_MOODS=%s;\n" % json.dumps(out, ensure_ascii=False, indent=0))
    print('wrote data/emotion-moods.js', len(out), 'keys')


main()

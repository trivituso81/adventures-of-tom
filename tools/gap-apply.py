#!/usr/bin/env python3
"""Pause after a spoken story line (linegap1, Tom 2026-11-18): docs/line-gaps.tsv -> data/line-gaps.js.

The tsv is hand-judged, one row per story line in play order: ch, scene, speaker, after, text.
`after` is how long the game holds once this line's clip has ended, before the next line or action:
  snap   0.15 s  the next person cuts in (a comeback, a scream, an instant answer)
  normal 0.65 s  ordinary turn (the game's default; a line with no row is normal)
  beat   1.25 s  a held moment before a deadpan, a confession or a stunned answer
The seconds live in DA_GAP in engine/dialog-auto.js. Only AUTO uses them (story scenes open with AUTO ON).
Edit the tsv as text, then: python3 tools/gap-apply.py     (--check: fail if the js is stale or a row is wrong)
Never hand-edit data/line-gaps.js. `text` must equal the line in data/scenes.js exactly.
"""
import json, os, sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV=os.path.join(ROOT,'docs','line-gaps.tsv'); OUT=os.path.join(ROOT,'data','line-gaps.js')
def build():
    scenes=open(os.path.join(ROOT,'data','scenes.js'),encoding='utf8').read()
    rows=[r.split('\t') for r in open(TSV,encoding='utf8').read().split('\n')[1:] if r.strip()]
    errs=[]; gaps={}
    for n,r in enumerate(rows,2):
        if len(r)!=5: errs.append('line %d: %d columns'%(n,len(r))); continue
        ch,scene,sp,after,text=r
        if after not in ('snap','normal','beat'): errs.append('line %d: after=%r'%(n,after))
        if json.dumps(text,ensure_ascii=False) not in scenes: errs.append('line %d: text not in data/scenes.js: %s'%(n,text[:50]))
        if 'SCENES.%s='%scene not in scenes: errs.append('line %d: no scene %s'%(n,scene))
        k=sp+'|'+text
        if k in gaps and gaps[k]!=after: errs.append('line %d: same speaker and text with two gaps: %s'%(n,text[:50]))
        if after!='normal': gaps[k]=after
    js='// GENERATED by tools/gap-apply.py from docs/line-gaps.tsv. Do not edit by hand.\nconst LINE_GAPS='+json.dumps(gaps,ensure_ascii=False,indent=0,sort_keys=True)+';\n'
    return js,errs,len(rows),len(gaps)
js,errs,n,g=build()
if errs: print('line-gaps: FAIL\n  '+'\n  '.join(errs)); sys.exit(1)
if '--check' in sys.argv:
    cur=open(OUT,encoding='utf8').read() if os.path.exists(OUT) else ''
    if cur!=js: print('line-gaps: FAIL data/line-gaps.js is stale: run python3 tools/gap-apply.py'); sys.exit(1)
    print('line-gaps: ok (%d rows, %d not normal)'%(n,g))
else:
    open(OUT,'w',encoding='utf8').write(js); print('wrote data/line-gaps.js: %d rows, %d not normal'%(n,g))

#!/usr/bin/env python3
"""Build data/emotion-reactions.js from docs/emotion-reactions.tsv for the chapters switched on (react2, Tom 2026-11-12).

    python3 tools/reaction-apply.py 1          # pilot: chapter 1 story scenes only
    python3 tools/reaction-apply.py 1 2 3      # later batches are cumulative

Only rows of kind `scene` are used (story dialogue). The tsv is the source: change a mood word, delete a row, add a row, rerun this tool.
Never hand-edit data/emotion-reactions.js. Key: '<Speaker>|<exact line text>|<chapter>' -> [[listener, mood], ...].
Fatal: a line whose listeners get two different moods in one chapter (needs a scene key; not needed in chapter 1).
"""
import csv, json, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, 'docs/emotion-reactions.tsv')
OUT = os.path.join(ROOT, 'data/emotion-reactions.js')

def main():
    want = sys.argv[1:]
    if not want: sys.exit(__doc__)
    table, clash = {}, []
    with open(TSV, newline='', encoding='utf-8') as fh:
        for r in csv.DictReader(fh, delimiter='\t', quoting=csv.QUOTE_NONE):
            ch = '21' if r['chapter'] == 'Nine Scoops' else r['chapter']
            if r['kind'] != 'scene' or ch not in want: continue
            key = '%s|%s|%s' % (r['speaker'], r['text'], ch)
            d = table.setdefault(key, {})
            if r['listener'] in d and d[r['listener']] != r['mood']: clash.append((key, r['listener']))
            d[r['listener']] = r['mood']
    if clash: sys.exit('clash: %r' % clash[:5])
    lines = ["'use strict';",
             "// data/emotion-reactions.js: GENERATED by tools/reaction-apply.py from docs/emotion-reactions.tsv. Do not hand-edit (corrections go in the tsv).",
             "// EMOTION_REACTIONS['<Speaker>|<exact line text>|<chapter>'] = [[listener pose id, mood], ...]. REACTION_CHAPTERS: chapters switched on (engine/emotions.js).",
             "const REACTION_CHAPTERS=new Set(%s);" % json.dumps([int(w) for w in want]),
             "const EMOTION_REACTIONS={"]
    for k in sorted(table):
        lines.append('%s: %s,' % (json.dumps(k, ensure_ascii=False), json.dumps([[a, b] for a, b in sorted(table[k].items())])))
    lines.append('};')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('wrote', len(table), 'lines,', sum(len(v) for v in table.values()), 'reactions')
main()

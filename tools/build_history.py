#!/usr/bin/env python3
"""Keeps data/build-history.js, the list the game shows when Tom taps the build label (welcome screen and menu).

Each entry: {"tag": build name, "at": ISO time the build was tagged for pushing, "what": one line of what changed}.
Newest first, one entry per line.

Usage (repo root):
  python3 tools/build_history.py add <TAG>   called by tools/art-library/bump_tags.py on every push; stamps TAG with the time now
  python3 tools/build_history.py sync        fills in builds found in the git log that the list lacks (also run by add)
  python3 tools/build_history.py check       exit 1 if the title stamp's build is not the newest entry

"what" comes from the build's heading in docs/CHANGES.md, else from its first commit subject.
On a rebase conflict in data/build-history.js: take upstream, then run `add <TAG>` again."""
import datetime, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'data', 'build-history.js')
HEAD = '// Generated by tools/build_history.py. Do not edit by hand. Newest first.\nconst BUILD_HISTORY=[\n'
TAG_RE = r'[A-Za-z][A-Za-z0-9_.-]*'


def load():
    if not os.path.exists(OUT): return []
    rows = []
    for line in open(OUT, encoding='utf-8'):
        line = line.strip().rstrip(',')
        if line.startswith('{'): rows.append(json.loads(line))
    return rows


def save(rows):
    rows.sort(key=lambda r: when(r['at']), reverse=True)
    body = ',\n'.join(json.dumps(r, ensure_ascii=False, separators=(',', ':')) for r in rows)
    open(OUT, 'w', encoding='utf-8').write(HEAD + body + '\n];\n')


def when(s):
    return datetime.datetime.fromisoformat(s.replace('Z', '+00:00'))


def changes_titles():
    """tag -> title, from both heading shapes in docs/CHANGES.md: `## tag (date): title` and `## date (tag): title`."""
    out = {}
    p = os.path.join(ROOT, 'docs', 'CHANGES.md')
    if not os.path.exists(p): return out
    for line in open(p, encoding='utf-8'):
        if not line.startswith('## '): continue
        m = re.match(r'## (%s) \(\d{4}-\d\d-\d\d[^)]*\): (.+)' % TAG_RE, line) or \
            re.match(r'## \d{4}-\d\d-\d\d \((%s)\): (.+)' % TAG_RE, line)
        if not m: continue
        title = re.sub(r'\s*\((?:no )?tag[^)]*\)\s*$', '', m.group(2).strip())
        out.setdefault(m.group(1), clean(title))
    return out


def clean(t):
    t = t.replace('—', ', ').replace('`', '').strip()
    return t[:1].upper() + t[1:]


def git_builds():
    """tag -> (latest commit time, first commit subject) for commits whose subject starts `tag: ` on the history at hand."""
    for ref in ('origin/main', 'HEAD'):
        r = subprocess.run(['git', 'log', '--format=%cI\t%s', ref], capture_output=True, text=True, cwd=ROOT)
        if r.returncode == 0: break
    else:
        return {}
    out = {}
    for line in r.stdout.splitlines():   # newest first
        at, _, subj = line.partition('\t')
        m = re.match(r'(%s): (.+)' % TAG_RE, subj)
        if not m or not re.search(r'\d', m.group(1)): continue   # build names end in a number (talk3, clips11)
        tag, rest = m.group(1), m.group(2)
        e = out.setdefault(tag, {'at': at, 'what': None})
        if not re.fullmatch(r'(version tags|bump tags|tags)', rest.strip()): e['what'] = clean(rest)
    return out


def sync(rows):
    have = {r['tag'] for r in rows}
    titles = changes_titles()
    n = 0
    for tag, e in git_builds().items():
        if tag in have: continue
        rows.append({'tag': tag, 'at': e['at'], 'what': titles.get(tag) or e['what'] or ''}); n += 1
    for r in rows:
        if titles.get(r['tag']) and r['what'] != titles[r['tag']]: r['what'] = titles[r['tag']]
    return n


def stamp_tag():
    m = re.search(r"d\.textContent='build ([^']*)'", open(os.path.join(ROOT, 'engine', 'main.js'), encoding='utf-8').read())
    return m.group(1) if m else None


def main():
    a = sys.argv[1:]
    if not a: print(__doc__); return 2
    rows = load()
    if a[0] == 'add' and len(a) == 2:
        if not re.fullmatch(r'[A-Za-z0-9_.-]+', a[1]): print('bad tag', a[1]); return 2
        n = sync(rows)
        now = datetime.datetime.now().astimezone().replace(microsecond=0).isoformat()
        rows = [r for r in rows if r['tag'] != a[1]]
        rows.append({'tag': a[1], 'at': now, 'what': changes_titles().get(a[1], '')})
        save(rows)
        print(f'build history: {a[1]} at {now}' + (f', {n} older build(s) filled in' if n else ''))
        return 0
    if a[0] == 'sync':
        n = sync(rows); save(rows); print(f'build history: {len(rows)} builds, {n} added'); return 0
    if a[0] == 'check':
        rows.sort(key=lambda r: when(r['at']), reverse=True)
        tag = stamp_tag()
        if not rows or rows[0]['tag'] != tag:
            print(f"build history: stamp is '{tag}' but the newest entry is '{rows[0]['tag'] if rows else None}': run `python3 tools/build_history.py add {tag}`")
            return 1
        print(f'build history ok ({len(rows)} builds, newest {tag})'); return 0
    print(__doc__); return 2


if __name__ == '__main__':
    sys.exit(main())

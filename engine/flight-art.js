'use strict';
// engine/flight-art.js: the painted flight scene (2026-10-30). Loaded before engine/travel.js, which asks it to draw each phase
// of the flight and falls back to its own pixel drawing when the art is not loaded (or fails to load).
//
//   cabin    seat 1A before takeoff (art/flight/cabin.webp), a slow pan so a tall phone shows all of it
//   takeoff  and landing: painted sky, skyline strip, ground strip, foreground strip, and the plane in nine poses
//   map      painted US map with pins, clouds and the top-view plane on its arc
//
// The strips are tiled mirrored (every other copy flipped), so the join never shows. Art sizes and anchors come from
// data/flight-art.js (generated by tools/sprite-bake/bake_flight.py). Everything is drawn in screen units (W x H).
const FLIGHT_ART={imgs:{},ready:false,failed:false,loading:false,cache:new Map()};
function flightArtLoad() {
  if(FLIGHT_ART.loading||typeof FLIGHT_ART_META==='undefined') return;
  FLIGHT_ART.loading=true;
  const M=FLIGHT_ART_META,keys=Object.keys(M.files); let left=keys.length;
  for(const k of keys) {
    const im=new Image();
    im.onload=()=>{ if(--left===0&&!FLIGHT_ART.failed) FLIGHT_ART.ready=true; };
    im.onerror=()=>{ FLIGHT_ART.failed=true; };
    im.src='art/flight/'+M.files[k]+'?v='+M.v;
    FLIGHT_ART.imgs[k]=im;
  }
}
setTimeout(flightArtLoad,2500);   // after the title is up; startTrip and the cab driver also ask for it
function flightArtReady() { return FLIGHT_ART.ready&&!FLIGHT_ART.failed; }

const fsEase=u=>{ u=Math.max(0,Math.min(1,u)); return u*u*(3-2*u); };
function fsSmooth(on) { const was=[gfx.imageSmoothingEnabled,gfx.imageSmoothingQuality]; gfx.imageSmoothingEnabled=on; if(on) gfx.imageSmoothingQuality='high'; return was; }
function fsRestore(was) { gfx.imageSmoothingEnabled=was[0]; gfx.imageSmoothingQuality=was[1]; }

// A strip at height h, tiled sideways. Tile n covers world x [n*dw, (n+1)*dw]; odd tiles are mirrored. off = world x at the screen's left edge.
function fsStrip(img,y,h,off) {
  const dw=img.naturalWidth*h/img.naturalHeight; if(dw<8) return;
  for(let n=Math.floor(off/dw);;n++) {
    const X=Math.floor(n*dw-off); if(X>=W) break;
    const w=Math.ceil(dw)+1;
    if(((n%2)+2)%2) { gfx.save(); gfx.translate(X+w,0); gfx.scale(-1,1); gfx.drawImage(img,0,y,w,h); gfx.restore(); }
    else gfx.drawImage(img,X,y,w,h);
  }
}
// A sky square covering the top region [0,regionH]: the sun is moved to targetY, as far as the picture's edges allow.
function fsSky(img,sun,regionH,targetY) {
  const s=Math.max(W,regionH)/img.naturalWidth,dw=img.naturalWidth*s,dh=img.naturalHeight*s;
  let oy=targetY-sun[1]*dh; oy=Math.min(0,Math.max(regionH-dh,oy));
  gfx.save(); gfx.beginPath(); gfx.rect(0,0,W,regionH); gfx.clip();
  gfx.drawImage(img,Math.round((W-dw)/2),Math.round(oy),Math.ceil(dw),Math.ceil(dh));
  gfx.restore();
}
// One sprite from an atlas, centred or by its bottom middle.
function fsProp(name,x,y,sc,alpha,opts) {
  const M=FLIGHT_ART_META,r=M.props[name]; if(!r) return;
  const w=r[2]*sc,h=r[3]*sc,o=opts||{};
  const pa=gfx.globalAlpha; gfx.globalAlpha=pa*(alpha==null?1:alpha);
  const dx=x-w/2,dy=o.bottom?y-h:y-h/2;
  if(o.shadow) { const sh=fsShadow(name); gfx.globalAlpha=pa*(o.shadow); gfx.drawImage(sh,r[0],r[1],r[2],r[3],dx+(o.sx||0),dy+(o.sy||0),w,h); gfx.globalAlpha=pa*(alpha==null?1:alpha); }
  gfx.drawImage(FLIGHT_ART.imgs.props,r[0],r[1],r[2],r[3],dx,dy,w,h);
  gfx.globalAlpha=pa;
}
// The props atlas as a dark silhouette (cached), for cloud and plane shadows. Canvas filters are missing on iPhone, so it is built by hand.
function fsShadow(name) {
  let c=FLIGHT_ART.cache.get('sh');
  if(!c) {
    const im=FLIGHT_ART.imgs.props; c=document.createElement('canvas'); c.width=im.naturalWidth; c.height=im.naturalHeight;
    const g=c.getContext('2d'); g.drawImage(im,0,0); g.globalCompositeOperation='source-in'; g.fillStyle='#0a1c3c'; g.fillRect(0,0,c.width,c.height);
    FLIGHT_ART.cache.set('sh',c);
  }
  return c;
}
// The map with its edges faded out, so it melts into the flat ocean around it. Cached per size.
function fsFeathered(img,dw,dh) {
  const key='map'+dw+'x'+dh; let c=FLIGHT_ART.cache.get(key); if(c) return c;
  c=document.createElement('canvas'); c.width=dw; c.height=dh; const g=c.getContext('2d');
  g.imageSmoothingEnabled=true; g.imageSmoothingQuality='high'; g.drawImage(img,0,0,dw,dh);
  g.globalCompositeOperation='destination-in';
  const fade=(x1,y1,len,span)=>{ const gr=g.createLinearGradient(0,0,x1,y1),f=Math.min(.45,len/span);
    gr.addColorStop(0,'rgba(0,0,0,0)'); gr.addColorStop(f,'#000'); gr.addColorStop(1-f,'#000'); gr.addColorStop(1,'rgba(0,0,0,0)');
    g.fillStyle=gr; g.fillRect(0,0,dw,dh); };
  fade(dw,0,Math.max(6,dw*.05),dw); fade(0,dh,Math.max(6,dh*.07),dh);
  FLIGHT_ART.cache.set(key,c); return c;
}

// ---------- Cabin ----------
function flightPaintedCabin(F) {
  if(!flightArtReady()) return false;
  const img=FLIGHT_ART.imgs.cabin,s=Math.max(W/img.naturalWidth,H/img.naturalHeight);
  const dw=img.naturalWidth*s,dh=img.naturalHeight*s,ox=dw-W,oy=dh-H,u=fsEase(F.t/2.6);
  // The square is cropped to the phone: portrait shows its middle half sideways, landscape a band down it. Pan across the rest.
  const x=ox>0?-ox*(.14+.72*u):-ox/2,y=oy>0?-oy*(.08+.55*u):-oy/2;
  const was=fsSmooth(true);
  gfx.drawImage(img,Math.round(x),Math.round(y),Math.ceil(dw),Math.ceil(dh));
  fsRestore(was);
  return true;
}

// ---------- Takeoff and landing, side view ----------
// The plane poses (data/flight-art.js plane[]): 0 taxi, 1 rotate, 2 climb gear down, 3 climb gear up, 4 cruise, 5 descend,
// 6 approach, 7 flare, 8 landing roll. Each has an anchor (middle of the body) and 'bot' (wheel bottom below the anchor).
function fsPlane(i,px,py,s,facing,ang) {
  const P=FLIGHT_ART_META.plane[i];
  gfx.save(); gfx.translate(px,py); if(ang) gfx.rotate(ang); gfx.scale(facing*s,s);
  gfx.drawImage(FLIGHT_ART.imgs.plane,P.x,P.y,P.w,P.h,-P.ax,-P.ay,P.w,P.h);
  gfx.restore();
}
function flightPaintedSide(F,time) {
  if(!flightArtReady()) return false;
  const M=FLIGHT_ART_META,I=FLIGHT_ART.imgs;
  const land=F.mode==='landing',west=F.dir==='west';
  const inLA=(F.mode==='takeoff')!==west;     // taking off from LA when flying east, landing in LA when flying west
  const facing=west?-1:1,K=inLA?'La':'Le',t=F.t;
  const was=fsSmooth(true);
  // Layout: the ground takes the lower half; the skyline stands on its top edge.
  const gy=Math.round(H*.5),gh=H-gy;
  const rw=M.runway[inLA?'la':'le'],yr=gy+gh*(rw[0]+(rw[1]-rw[0])*.55);   // the line the wheels run on
  // Speed: the scenery slides under the plane while it rolls, then slows as it climbs away (the old scroll rule, in screen units).
  const speed=land?(t<2.6?60:Math.max(0,60*(1-(t-2.6)/1.4))):Math.min(70,t*40);
  const S=Math.max(2,Math.min(5,Math.round(W/140)));
  const scroll=(F.scroll=(F.scroll||0)+speed*.016*(F.last!=null?Math.min(3,(time-F.last)*60):1)); F.last=time;
  const drift=-facing*scroll*S;                   // world x at the screen's left edge is -drift (times the layer's speed)
  // Sky, with the sun put just above the skyline (LA, a low sunset) or high (Long Island).
  fsSky(I['sky'+K],M.sun[inLA?'la':'le'],gy+8,inLA?gy*.78:gy*.4);
  // Skyline stands on the ground's top edge.
  const skImg=I['skyline'+K],skH=Math.round(Math.max(H*(inLA?.31:.27),W*.17*(inLA?1.25:1)));
  fsStrip(skImg,gy-skH+4,skH,-drift*.3);
  // Ground, then the plane's shadow and the plane.
  fsStrip(I['ground'+K],gy,gh,-drift);
  const L=Math.min(W*.6,H*.8,560),s=L/M.plane[0].w;
  let px=W/2,py,frame,alt;
  if(!land) {
    const lift=t<1.7?0:Math.pow((t-1.7)/2.3,1.4); alt=lift;
    frame=t<1.45?0:t<1.95?1:t<2.75?2:3;
    py=yr-M.plane[0].bot*s-lift*H*.34; px+=facing*lift*W*.10;
  } else {
    const k=Math.min(1,t/2.6),e=1-Math.pow(1-k,2); alt=1-e;
    frame=t<.8?5:t<1.7?6:t<2.6?7:8;
    py=yr-M.plane[8].bot*s-(1-e)*H*.30; px-=facing*(1-e)*W*.14;
  }
  gfx.globalAlpha=.3; ellipse(px,yr+s*4,L*.46*(1-.35*Math.min(1,alt)),L*.035,'#0a0a14'); gfx.globalAlpha=1;
  fsPlane(frame,px,py,s,facing,0);
  // Tire smoke at touchdown.
  if(land&&t>2.55&&t<3.5) { const q=(t-2.55)/.95; fsProp('smoke',px-facing*(.02+.35*q)*L,yr-s*6,s*(.35+.5*q),(1-q)*.8,{bottom:true}); }
  // Foreground plants, the fastest layer, in front of everything.
  const fgImg=I['fore'+K],fgH=Math.round(H*.2);
  fsStrip(fgImg,H-fgH,fgH,-drift*1.6);
  fsRestore(was);
  // Caption.
  const cap=land?(inLA?'LOS ANGELES':'LONG ISLAND'):(inLA?'LEAVING LOS ANGELES':'LEAVING LONG ISLAND');
  const ls=Math.max(2,Math.round(Math.min(W,H*1.2)/180));
  const cy=safeTop+Math.round(50/scale); label(cap,W/2+1,cy+1,'#1b2d27',ls); label(cap,W/2,cy,'#fff1cb',ls);
  return true;
}

// ---------- Across the country ----------
function fsCurve(a,b,u,lift) {
  const mx=(a[0]+b[0])/2,my=(a[1]+b[1])/2-lift;
  const x=(1-u)*(1-u)*a[0]+2*(1-u)*u*mx+u*u*b[0],y=(1-u)*(1-u)*a[1]+2*(1-u)*u*my+u*u*b[1];
  const dx=2*(1-u)*(mx-a[0])+2*u*(b[0]-mx),dy=2*(1-u)*(my-a[1])+2*u*(b[1]-my);
  return {x,y,dx,dy,ang:Math.atan2(dy,dx)};
}
function flightPaintedMap(F,time) {
  if(!flightArtReady()) return false;
  const M=FLIGHT_ART_META,I=FLIGHT_ART.imgs,mp=M.map,MW=mp.w,MH=mp.h;
  const reserve=(layout.landscape?162:300)/scale,top=safeTop+4,availH=Math.max(60,H-top-reserve);
  const sc=Math.min(W/MW,availH/MH),dw=Math.round(MW*sc),dh=Math.round(MH*sc);
  const ox=Math.round((W-dw)/2),oy=Math.round(top+(availH-dh)/2);
  const was=fsSmooth(true);
  // Ocean all the way out, with little waves, then the painting with soft edges.
  rect(0,0,W,H,mp.ocean);
  for(let i=0;i<70;i++) { const n=hash(i,31),wx=n%W,wy=(n>>>9)%H,ph=Math.floor(time*1.5+i)%3; if(ph) rect(wx,wy,6,1,mp.wave); }
  gfx.drawImage(fsFeathered(I.map,dw,dh),ox,oy);
  const P=(p)=>[ox+p[0]*sc,oy+p[1]*sc];
  const a=F.dir==='west'?mp.le:mp.la,b=F.dir==='west'?mp.la:mp.le,west=F.dir==='west';
  const u=Math.min(1,Math.max(0,(F.t-.6)/6.6)),e=u<.5?2*u*u:1-Math.pow(-2*u+2,2)/2;
  const lift=MH*.2;
  // Trail of dots.
  const ds=Math.max(.055,sc*.28);
  for(let k=0;k<=60;k++) { if(k%3===2) continue; const q=k/60*e,c=fsCurve(a,b,q,lift),[sx,sy]=P([c.x,c.y]); fsProp('dot',sx,sy,ds,1); }
  // Pins (their tips are the towns), bobbing a little.
  const pins=(p,name)=>{ const [sx,sy]=P(p),ps=Math.max(sc*.5,22/177),bob=Math.round(Math.sin(time*3+(name==='pinHome'?0:2))*1.5); fsProp(name,sx,sy+bob,ps,1,{bottom:true}); };
  pins(mp.le,'pinHome'); pins(mp.la,'pinAway');
  const ls=Math.max(1,Math.min(2,Math.round(W/220)));
  const tag=(txt,x,y)=>{ const w=(txt.length*4-1)*ls,cx=clamp(x,w/2+4,W-w/2-4); rect(cx-w/2-3,y-2,w+6,5*ls+4,'#1d2430cc'); label(txt,cx,y,'#fff1cb',ls); };
  { const [lx,ly]=P(mp.le),[ax,ay]=P(mp.la); tag('LONG ISLAND',lx-(43*ls)/2-6*ls,ly+10*ls); tag('LOS ANGELES',ax+(43*ls)/2+6*ls,ay+6*ls); }
  // A compass star in the corner.
  fsProp('star',ox+dw*.93,oy+dh*.13,Math.max(.12,sc*.34),.95);
  // Clouds with shadows, drifting east.
  const cn=['cloudA','cloudB','cloudC','cloudD','cloudE','cloudF'];
  for(let i=0;i<6;i++) {
    const n=hash(i,77),cs=sc*(.55+(n%4)*.12);
    const cx=(((n%MW)+time*(26+i*11))%(MW+500))-250,cy=MH*(.1+.8*((n>>>8)%100)/100);
    const [sx,sy]=P([cx,cy]);
    if(sx<-120||sx>W+120) continue;
    fsProp(cn[i],sx,sy,cs,.92,{shadow:.22,sx:14*cs,sy:30*cs});
  }
  // Contrail puffs behind the plane, then the plane itself, drawn along its arc.
  const c=fsCurve(a,b,e,lift),[px,py]=P([c.x,c.y]);
  const pls=Math.max(sc*.62,46/280);
  for(let j=7;j>=1;j--) { const q=e-j*.012; if(q<=0) continue; const cc=fsCurve(a,b,q,lift),[qx,qy]=P([cc.x,cc.y]); fsProp('puff',qx,qy,pls*.2*(1+j*.14),.7*(1-j/8)); }
  // Heading left: draw the mirrored sprite so the light stays on the upper left. (rotate then mirror: the nose ends up along the heading)
  const left=c.dx<0,turn=fsCurve(a,b,Math.min(1,e+.02),lift).ang-fsCurve(a,b,Math.max(0,e-.02),lift).ang;
  const tn=Math.abs(turn)>1e-4?(left?-turn:turn):0;
  const name=(e<.08||e>.92)?(tn>0?'planeB2':'planeB1'):'planeLvl';
  gfx.save(); gfx.translate(px,py);
  if(left) { gfx.rotate(Math.atan2(-c.dy,-c.dx)); gfx.scale(-1,1); } else gfx.rotate(c.ang);
  fsProp(name,0,0,pls,1,{shadow:.28,sx:5*pls,sy:12*pls});
  gfx.restore();
  fsRestore(was);
  // Header and time left.
  const hs=Math.max(1,Math.min(2,Math.round(W/200)));
  const route=west?'LONG ISLAND > LOS ANGELES':'LOS ANGELES > LONG ISLAND';
  label(route,W/2+1,oy-2*hs+1,'#05204a',hs); label(route,W/2,oy-2*hs,'#fff1cb',hs);
  const left2=Math.max(0,Math.round((1-e)*360)),hh=Math.floor(left2/60),mm=left2%60;
  const tl=left2?hh+'H '+String(mm).padStart(2,'0')+'M TO GO':'ARRIVING';
  label(tl,W/2+1,oy+dh+4*hs+1,'#05204a',hs); label(tl,W/2,oy+dh+4*hs,'#ffd968',hs);
  return true;
}
